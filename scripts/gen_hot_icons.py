#!/usr/bin/env python3
"""Generate src/components/hot_icons.rs from heat-dashboard's Template Generator icons.

Usage: scripts/gen_hot_icons.py <heat-dashboard checkout> > src/components/hot_icons.rs

heat-dashboard (https://opendev.org/openstack/heat-dashboard, Apache 2.0) draws each of the
18 generator types with its own SVG, in
heat_dashboard/static/dashboard/project/heat_dashboard/template_generator/js/resources/
os__<service>__<type>/os__<service>__<type>.svg (55x55, a ring and a black glyph; the -gray,
-blue, -green and -red files are the same drawing in other colours). This keeps the black one,
drops editor leftovers (ids, classes, titles, empty attributes, invisible elements) and turns its
colours into `currentColor` (ink) and the `bg` class (white cut-outs and the ring's fill), so CSS
colours the icon as Horizon recolours its files.
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SVG = "{http://www.w3.org/2000/svg}"
RESOURCES = "heat_dashboard/static/dashboard/project/heat_dashboard/template_generator/js/resources"
WHITE = {"white", "#fff", "#ffffff"}
NONE = {"none", "transparent"}
KEEP = {
    "d", "points", "x", "y", "x1", "y1", "x2", "y2", "cx", "cy", "r", "rx", "ry", "width",
    "height", "transform", "fill", "stroke", "stroke-width", "stroke-linecap",
    "stroke-linejoin", "stroke-miterlimit", "fill-rule", "font-size", "font-family",
    "font-weight", "text-anchor",
}
STYLE_KEEP = {"fill", "stroke", "stroke-width", "font-size", "font-family", "font-weight"}


def num(s: str) -> str:
    """Numbers shortened to 3 decimals: the files carry 16, invisible at 55 px."""
    return re.sub(r"-?\d+\.\d+(?:e-?\d+)?", lambda m: f"{float(m.group()):.3f}".rstrip("0").rstrip("."), s)


def clean(el: ET.Element) -> str | None:
    tag = el.tag.replace(SVG, "")
    if tag in ("title", "defs", "metadata"):
        return None
    attrs = {k: v.strip() for k, v in el.attrib.items() if v.strip()}
    for decl in attrs.pop("style", "").split(";"):
        if ":" in decl:
            k, v = (x.strip() for x in decl.split(":", 1))
            if k in STYLE_KEEP and v:
                attrs[k] = v
    attrs = {k: v for k, v in attrs.items() if k in KEEP}
    if attrs.get("transform", "x") == "":
        attrs.pop("transform")
    classes = []
    for prop in ("fill", "stroke"):
        v = attrs.get(prop, "").lower()
        if v in WHITE:
            attrs.pop(prop)
            classes.append(f"bg-{prop[0]}")
        elif v and v not in NONE:
            attrs[prop] = "currentColor"
    if attrs.get("font-family"):
        attrs["font-family"] = "Helvetica, Arial, sans-serif"
    children = [c for c in (clean(c) for c in el) if c]
    text = (el.text or "").strip()
    if tag == "g" and not children:
        return None
    if tag == "rect" and attrs.get("fill", "") == "none" and attrs.get("stroke", "none") == "none":
        return None
    out = f"<{tag}"
    if classes:
        out += f' class="{" ".join(classes)}"'
    for k, v in attrs.items():
        out += f' {k}="{num(v) if k in ("d", "points", "transform") or k[0] in "xyrcwh" else v}"'
    if not children and not text:
        return out + "/>"
    return out + ">" + text + "".join(children) + f"</{tag}>"


def main() -> None:
    root = Path(sys.argv[1]) / RESOURCES
    entries = []
    for d in sorted(root.iterdir()):
        if not d.name.startswith("os__"):
            continue
        svg = ET.parse(d / f"{d.name}.svg").getroot()
        body = "".join(c for c in (clean(c) for c in svg) if c)
        entries.append((d.name, body))
    print("//! Heat resource icons of the *Template Generator*: heat-dashboard's own SVGs")
    print("//! (`template_generator/js/resources/os__*/os__*.svg`, 55×55: a ring and a glyph),")
    print("//! from <https://opendev.org/openstack/heat-dashboard> (Apache 2.0, © OpenStack")
    print("//! Foundation). Generated by `scripts/gen_hot_icons.py`: regenerate rather than edit.")
    print("//!")
    print("//! Colours are `currentColor` (the glyph and the ring) and the class `bg-f` / `bg-s`")
    print("//! (white cut-outs, filled or stroked), so CSS colours them, as Horizon swaps its")
    print("//! gray, blue and red copies of each file.")
    print()
    print("/// Side of the box the icons are drawn in (`viewBox=\"0 0 55 55\"`).")
    print("pub const BOX: f64 = 55.0;")
    print()
    print("/// The icon's SVG markup (children of an `<svg viewBox=\"0 0 55 55\">`), for one of")
    print("/// Horizon's 18 generator types; `None` for any other type.")
    print("pub fn markup(kind: &str) -> Option<&'static str> {")
    print("    Some(match kind.to_ascii_lowercase().replace(\"::\", \"__\").as_str() {")
    for name, body in entries:
        print(f'        "{name}" => r##"{body}"##,')
    print("        _ => return None,")
    print("    })")
    print("}")
    print()
    print("#[cfg(test)]")
    print("mod tests {")
    print("    use super::*;")
    print()
    print("    #[test]")
    print("    fn every_palette_type_has_an_icon() {")
    print("        for (_, kinds) in crate::components::hot::PALETTE {")
    print("            for k in *kinds {")
    print("                let m = markup(k).unwrap_or_else(|| panic!(\"no icon for {k}\"));")
    print("                assert!(m.contains(\"currentColor\"), \"{k}\");")
    print("                assert!(!m.contains(\"id=\") && !m.contains(\"<title\"), \"{k}: editor leftovers\");")
    print("            }")
    print("        }")
    print("        assert_eq!(markup(\"OS::Octavia::Pool\"), None);")
    print("    }")
    print("}")


if __name__ == "__main__":
    main()
